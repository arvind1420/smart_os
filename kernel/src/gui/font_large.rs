/// High-resolution bitmap font for Smart OS (10x20 pixels per glyph).
///
/// Provides a larger, more readable font for the text editor and
/// applications requiring better text clarity.
///
/// Each glyph is 20 rows of u16, where the top 10 bits (bits 15-6)
/// represent pixels. Bit 15 = leftmost pixel, bit 6 = rightmost pixel.

pub const FONT_LARGE_W: usize = 10;
pub const FONT_LARGE_H: usize = 20;

/// Font size selector for the GUI system.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum FontSize {
    /// 8x16 pixel font (existing compact font).
    Small,
    /// 10x20 pixel font (new high-resolution font).
    Large,
}

/// Get the bitmap data for an ASCII character in the large font.
/// Returns 20 u16 values, each representing one row (top 10 bits = pixels).
pub fn get_large_char(c: u8) -> &'static [u16; 20] {
    let idx = if c >= 32 && c <= 126 {
        (c - 32) as usize
    } else {
        0 // Space for unknown chars
    };
    if idx < FONT_LARGE_DATA.len() {
        &FONT_LARGE_DATA[idx]
    } else {
        &FONT_LARGE_DATA[0]
    }
}

/// Get the character width for a given font size.
pub fn char_width(size: FontSize) -> usize {
    match size {
        FontSize::Small => 8,
        FontSize::Large => FONT_LARGE_W,
    }
}

/// Get the character height for a given font size.
pub fn char_height(size: FontSize) -> usize {
    match size {
        FontSize::Small => 16,
        FontSize::Large => FONT_LARGE_H,
    }
}

